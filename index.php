    <h2 id="progress">A simple way to track your progress</h2>
    <p>Many readers tell us it helps to tick off each lesson as they finish it. Here is a checklist you can follow — print it out if you like, using the button on any guide.</p>
    <ul>
      <li>I can open the Start menu and find my programs.</li>
      <li>I can open, read, and send an email.</li>
      <li>I can connect to my home Wi-Fi.</li>
      <li>I can print a page.</li>
      <li>I can make a video call to someone I love.</li>
      <li>I can tell a real message from a scam.</li>
    </ul>
