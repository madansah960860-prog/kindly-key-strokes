  <h2 id="who-for">Who these lessons are for</h2>
  <p>We wrote Kindly Keystrokes for the person who feels a quiet flutter of nerves when the screen lights up. Perhaps you have just been given a laptop by a well-meaning relative. Perhaps you have used a computer a little at work, years ago, and everything has changed since. Perhaps you simply never got the chance to learn and would rather not announce that to the whole family. Wherever you are starting, you are welcome here, and you are starting from exactly the right place.</p>
  <p>You will not find any assumption that you already know the words. You will not find anyone tapping their foot while you find the mouse. What you will find is small steps, plain language, and the patience to go over a thing twice if twice is what it takes. Learning a computer later in life is not harder than learning it young — it simply deserves to be taught kindly, and that is the whole promise of this site.</p>

  <h2 id="how-to-use">How to use this site comfortably</h2>
  <p>Look at the top of any page for the words <strong>Text size</strong> with three buttons: A, A+, and A++. Press A+ or A++ to make every word on the site larger, and it will stay that way on your device until you change it back. Each long lesson also has a <strong>Print this guide</strong> button, so you can keep a paper copy next to the computer while you practice.</p>
  <p>Above every page you will see a dark blue reminder bar. Please read it once and remember it: a genuine help website like this one is for reading only. We will never telephone you, never ask to take over your screen, and never ask for money. Anyone who does is not us.</p>

  <h2 id="what-this-is">What Kindly Keystrokes is — and is not</h2>
  <p>This is an independent educational website. Everything on it is free to read. We do not sell anything, we do not offer repairs or paid help, and we have no way to reach into your computer. When we mention a company such as Microsoft, Google, or a printer maker, we do it only to teach; we are not connected to them in any way.</p>
  <p>When your computer needs something only its maker can do — recovering a locked account, honoring a warranty, arranging a repair — we will point you to that company's own official website, which you can reach by typing its address yourself. That is always the safe path, and we will show you how to walk it.</p>
  <p>And if you ever feel stuck, that is not a sign you are doing it wrong — it is simply the moment to slow down, read the step once more, and try again. Every confident computer user was once exactly where you are now.</p>
