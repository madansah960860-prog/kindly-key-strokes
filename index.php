  <h1>Computers and email, explained kindly</h1>
  <p class="hero__lead">Kindly Keystrokes is a free place to learn your computer at your own pace. No rush, no jargon, and no one looking over your shoulder — just clear, patient lessons you can follow one step at a time.</p>
</div>
<figure class="figure figure--hero col">
  <img src="assets/img/home-hero.webp" alt="An older woman sitting comfortably at a table, using a laptop computer." width="1024" height="678">

</figure>
<div class="col">
  <p>If a computer still feels like a stranger in your home, you are in good company. Plenty of thoughtful, capable people reach their fifties, sixties, seventies and beyond without ever needing one — and then a grandchild moves away, a doctor's office goes online, or a bank closes its local branch, and suddenly the computer matters. The good news is that none of this is beyond you. It was built by people, and people can learn it.</p>

  <p>These lessons are written the way a patient friend would explain things across the kitchen table. We use plain words. We define anything technical the first time it appears. We show you exactly where to click, and we tell you what you should see when you get there. When something can go wrong, we say so, and we tell you how to put it right.</p>

  <h2 id="start-here">Start here: five lessons, in order</h2>
  <p>You do not have to read everything at once. Pick Lesson 1, give it twenty quiet minutes, and stop when you like. Each lesson stands on its own, but they also build on one another, so working through them in order is the gentlest path. There is no test at the end and no one keeping score — only you, learning something useful at whatever pace suits you.</p>
